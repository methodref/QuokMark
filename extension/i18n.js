function t(text,values={}){
  const translated=translations[language]?.[text] ?? text;
  return translated.replace(/\{(\w+)\}/g,(_,key)=>String(values[key] ?? ''));
}
const uiTexts=[], uiAttributes=[];
const textWalker=document.createTreeWalker(document.documentElement,NodeFilter.SHOW_TEXT);
while(textWalker.nextNode()){
  const node=textWalker.currentNode, text=node.textContent.trim();
  if(Object.hasOwn(translations.en,text))uiTexts.push({node,text,original:node.textContent});
}
for(const node of document.querySelectorAll('[aria-label], [placeholder], [title]')){
  for(const attr of ['aria-label','placeholder','title']){
    const text=node.getAttribute(attr);
    if(text && Object.hasOwn(translations.en,text))uiAttributes.push({node,attr,text});
  }
}
function applyLanguage(){
  document.documentElement.lang=language==='zh'?'zh-CN':language;
  for(const {node,text,original} of uiTexts)node.textContent=original.replace(text,t(text));
  for(const {node,attr,text} of uiAttributes)node.setAttribute(attr,t(text));
  document.getElementById('language-select').value=language;
}
async function loadLanguage(){
  try{
    const saved=(startupData?.settings || await chrome.storage.local.get('linkcoveLanguage')).linkcoveLanguage;
    language=Object.hasOwn(translations,saved)?saved:'zh';
  }catch{language='zh';}
  applyLanguage();
}
document.getElementById('language-select').addEventListener('change',async event=>{
  const input=event.target, next=input.value;input.disabled=true;
  try{
    await chrome.storage.local.set({linkcoveLanguage:next});
    language=next;applyLanguage();message();render();showBookmarkTip(null);
  }catch{input.value=language;message(t('语言保存失败，请重试'));}
  finally{input.disabled=false;input.focus();}
});
